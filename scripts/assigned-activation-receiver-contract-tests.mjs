import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const root = new URL('../mobile/plugins/custodial-native-vault/android/src/main/', import.meta.url);
const receiver = readFileSync(new URL('java/org/memphiszoo/custodial/vault/AssignedDeviceActivationReceiver.java', root), 'utf8');
const manifest = readFileSync(new URL('AndroidManifest.xml', root), 'utf8');
assert.match(manifest, /AssignedDeviceActivationReceiver[\s\S]*?android:permission="android.permission.DUMP"/);
assert.match(receiver, /engine\.activateAssignedDevice\(operationId, deviceId, activationSecret\)/);
assert.doesNotMatch(receiver, /engine\.enroll\(/, 'receiver must use the protected state-derived activation owner');
assert.match(receiver, /VaultValidation\.wipe\(activationSecret\)/);
assert.doesNotMatch(receiver, /Log\.[a-z]+\([^;]*(?:rawToken|activationSecret|token)/);
assert.match(receiver,/engine\.reportAssignedActivation\(/);
assert.match(receiver,/journal\.captureTransportResult\(operationId,state,accepted\)/);
assert.match(receiver,/pending\.setResultData\(body\.toString\(\)\)/);
assert.match(receiver,/journal\.transportResultFor\(operationId,state\)/);
assert.doesNotMatch(receiver,/put\("(?:credential|employee|installation_seal|activation_token)/);
const policy=readFileSync(new URL('java/org/memphiszoo/custodial/vault/RequestPolicy.java',root),'utf8');
assert.match(policy,/CREDENTIAL_MANAGEMENT_PREFIXES[\s\S]*?"\/custodial-device-auth\/"/);
const plugin=readFileSync(new URL('java/org/memphiszoo/custodial/vault/CustodialNativeVaultPlugin.java',root),'utf8');
assert.doesNotMatch(plugin,/reportAssignedActivation|captureTransportResult|activateAssignedDevice/,'no WebView maintenance write bridge');
console.log('ASSIGNED_ACTIVATION_RECEIVER_CONTRACT_PASS');
